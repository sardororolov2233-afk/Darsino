import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const folder = new URL("../supabase/migrations/", import.meta.url);
const names = (await readdir(folder)).filter((n) => n.endsWith(".sql")).sort();
const parts = await Promise.all(
  names.map((n) => readFile(new URL(n, folder), "utf8")),
);
const body = (sql) =>
  sql
    .replace(/^begin;\s*$/m, "")
    .replace(/^commit;\s*$/m, "")
    .trim();
const coreTables = [
  "profiles",
  "tutors",
  "offerings",
  "sessions",
  "applications",
  "enrollments",
  "attendance",
  "reviews",
  "messages",
  "notifications",
  "favorites",
];
const output = `-- DARSINO: Supabase SQL Editor installer (generated; do not edit this file).
-- Source: migrations/*.sql. Regenerate with npm run supabase:bundle.
-- Run as the project postgres administrator. Creates/updates only Darsino objects,
-- private buckets, Darsino Storage policies and the Auth profile trigger.
-- Supports an empty project OR the original Darsino marketplace schema.
-- Safe to run again; existing users, lessons and binary files are retained.
begin;
do $darsino_install$
declare existing integer;
begin
  if to_regclass('storage.objects') is null or to_regclass('auth.users') is null then
    raise exception 'Run this installer in a Supabase project (Auth and Storage schemas are required).';
  end if;
  select count(*) into existing from unnest(array[${coreTables.map((n) => `'darsino_${n}'`).join(",")}]) t
    where to_regclass('public.'||t) is not null;
  if existing=0 then
    execute $darsino_baseline$
${body(parts[0])}
$darsino_baseline$;
  elsif existing<>${coreTables.length} or to_regprocedure('public.darsino_snapshot()') is null or to_regprocedure('public.darsino_mutate(jsonb)') is null then
    raise exception 'Incomplete Darsino schema. Restore the original migration before upgrading; this installer never drops existing tables.';
  end if;
end $darsino_install$;

${parts
  .slice(1)
  .map((sql, i) => `-- Source: ${names[i + 1]}\n${body(sql)}`)
  .join("\n\n")}

commit;
`;
const target = new URL(
  "../supabase/Darsino_Supabase_setup.sql",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error("Supabase bundle is stale. Run npm run supabase:bundle.");
  console.log("Supabase SQL bundle matches migrations.");
} else {
  await writeFile(target, output);
  console.log(`Supabase SQL ready: ${fileURLToPath(target)}`);
}
